export type Messages = (typeof MESSAGES)[Locale];
type HeaderLike = Pick<Headers, "get">;

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "zh";
}

export function resolveLocale(value: string | null | undefined): Locale {
  return value === "zh" ? "zh" : DEFAULT_LOCALE;
}

export function readCookieValue(
  cookieHeader: string | null | undefined,
  cookieName: string,
) {
  if (!cookieHeader) {
    return undefined;
  }

  for (const fragment of cookieHeader.split(";")) {
    const trimmed = fragment.trim();
    if (!trimmed) {
      continue;
    }

    const separatorIndex = trimmed.indexOf("=");
    const name =
      separatorIndex === -1 ? trimmed : trimmed.slice(0, separatorIndex);
    if (name !== cookieName) {
      continue;
    }

    const value =
      separatorIndex === -1 ? "" : trimmed.slice(separatorIndex + 1);
    try {
      return decodeURIComponent(value);
    } catch {
      return value;
    }
  }

  return undefined;
}

export function resolveRequestLocale(
  headers: HeaderLike,
  fallbackLocale: string | null | undefined = DEFAULT_LOCALE,
): Locale {
  const cookieLocale = readCookieValue(
    headers.get("cookie"),
    LOCALE_COOKIE_NAME,
  );
  if (isLocale(cookieLocale)) {
    return cookieLocale;
  }

  return resolveLocale(fallbackLocale);
}

export function getMessages(locale: Locale) {
  return MESSAGES[locale];
}

export function getUploadFileTooLargeMessage(
  locale: Locale,
  maxUploadMb: number,
) {
  return MESSAGES[locale].errors.uploadFileTooLarge.replace(
    "{maxUploadMb}",
    String(maxUploadMb),
  );
}
